        ,@("state only $fffd no player", "state only $em no player")
        ,@('state only ? no player', "state only $em no player")
        ,@("alcove $fffd not 16", "alcove $em not 16")
        ,@('alcove ? not 16', "alcove $em not 16")
        ,@('fog ? solid', "fog $arr solid")
        ,@('(3+ ? `', "(3+ $arr ``")
        ,@("(3+ $fffd ``", "(3+ $arr ``")
        ,@(') ? features', ") $arr features")
        ,@(') ? floor', ") $arr floor")
        ,@("labels $fffd they live", "labels $em they live")

        ,@('combat-scene.md) ? [Game', "combat-scene.md) $em [Game")
        ,@("[ADR 002 $fffd Mapping", "[ADR 002 $em Mapping")
        ,@('[ADR 002 ? Mapping', "[ADR 002 $em Mapping")
        ,@("[ADR 005 $fffd FOE", "[ADR 005 $em FOE")
        ,@('[ADR 005 ? FOE', "[ADR 005 $em FOE")
        ,@("patrol.md) $fffd [ADR 014", "patrol.md) $em [ADR 014")
        ,@('patrol.md) ? [ADR 014', "patrol.md) $em [ADR 014")
        ,@("[ADR 014 $fffd launch", "[ADR 014 $em launch")
        ,@('[ADR 014 ? launch', "[ADR 014 $em launch")
        ,@("[ADR 019 $fffd Floor", "[ADR 019 $em Floor")
        ,@('[ADR 019 ? Floor', "[ADR 019 $em Floor")
        ,@("[04 $fffd Tech", "[04 $em Tech")
        ,@('[04 ? Tech', "[04 $em Tech")
        ,@("events ? ``MapSystem``", "events $arr ``MapSystem``")
        ,@("events $fffd ``MapSystem``", "events $arr ``MapSystem``")
        ,@("LeaveHub` $fffd S1:", "LeaveHub` $em S1:")
    )

    foreach ($pair in $pairs) {
        $content = $content.Replace($pair[0], $pair[1])
    }

    $content = $content.Replace("(3+ $arr ``$fffd``)", "(3+ $arr ``?``)")
    $content = $content.Replace("floor ``$fffd``", 'floor `?`')

    if ($content.IndexOf($fffd) -ge 0) {
        $content = $content.Replace([string]$fffd, [string]$em)
    }

    return $content
}

foreach ($path in $Paths) {
    $full = [System.IO.Path]::GetFullPath($path)
    if (-not (Test-Path $full)) {
        Write-Warning "Skip missing: $full"
        continue
    }
    $before = [System.IO.File]::ReadAllText($full)
    $after = Fix-DocEncoding $before
    if ($before -ne $after) {
        [System.IO.File]::WriteAllText($full, $after, $utf8NoBom)
        Write-Host "Fixed: $full"
    }
    else {
        Write-Host "No changes: $full"
    }
}

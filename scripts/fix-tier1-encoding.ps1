# One-shot encoding repair for phase C tier-1 docs (game-phase.md, mapping.md).
param(
    [string[]]$Paths = @(
        (Join-Path (Join-Path $PSScriptRoot '..') 'docs\02-systems\game-phase.md'),
        (Join-Path (Join-Path $PSScriptRoot '..') 'docs\02-systems\mapping.md')
    )
)

$utf8NoBom = New-Object System.Text.UTF8Encoding $false
$fffd = [char]0xFFFD
$arr = [char]0x2192   # right arrow
$em = [char]0x2014    # em dash
$en = [char]0x2013    # en dash
$ell = [char]0x2026    # ellipsis
$sect = [char]0x00A7  # section sign

function Fix-DocEncoding([string]$content) {
    $content = $content.Replace("spec$fffd" + 'd', "spec'd")
    $content = $content.Replace("party$fffd" + 's', "party's")
    $content = $content.Replace("$fffd" + '7)', "$sect" + '7)')
    $content = $content.Replace("$fffd" + 'return to hub.' + "$fffd", "'return to hub.'")
    $content = $content.Replace("$fffd" + 'hub only.' + "$fffd", "'hub only.'")

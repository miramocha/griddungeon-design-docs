    $content = $content.Replace("$fffd" + 'incoming FOE' + "$fffd", "'incoming FOE'")
    $content = $content.Replace('[? Consider', "[$sect Consider")
    $content = $content.Replace('? Consider / explore', "$sect Consider / explore")
    $content = $content.Replace("ContentDatabase, $fffd", "ContentDatabase, $ell")
    $content = $content.Replace('ContentDatabase, ?', "ContentDatabase, $ell")
    $content = $content.Replace('F1?F4', "F1$en" + 'F4')
    $content = $content.Replace("F1$fffd" + 'F4', "F1$en" + 'F4')
    $content = $content.Replace("GamePhaseController.cs $fffd plain", "GamePhaseController.cs $em plain")
    $content = $content.Replace('GamePhaseController.cs ? plain', "GamePhaseController.cs $em plain")

